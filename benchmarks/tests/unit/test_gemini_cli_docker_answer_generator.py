import pytest
import os
import json
from unittest.mock import MagicMock, patch, AsyncMock
from benchmarks.answer_generators.gemini_cli_docker_answer_generator import GeminiCliDockerAnswerGenerator
from benchmarks.data_models import ApiUnderstandingBenchmarkCase, AnswerTemplate

@pytest.mark.asyncio
async def test_docker_command_construction_api_key():
    """Test that Docker command is constructed correctly with GEMINI_API_KEY."""

    with patch.dict(os.environ, {"GEMINI_API_KEY": "test-key"}, clear=True):
        generator = GeminiCliDockerAnswerGenerator(
            model_name="gemini-2.5-flash",
            image_name="my-image:latest"
        )

        # The CLI with --output-format json returns a JSON object with a "response" key.
        # The value of "response" is the text generated by the model.
        # Since the model is prompted to output JSON, this text will be a JSON string (likely with markdown).
        inner_model_json = {
            "code": "class Test:",
            "fully_qualified_class_name": "test.Test",
            "rationale": "Because."
        }
        # Simulate model outputting markdown-wrapped JSON
        model_text_output = f"```json\n{json.dumps(inner_model_json)}\n```"
        
        # The actual CLI stdout is a JSON object containing this text
        cli_output = {
            "response": model_text_output
        }
        
        stdout_bytes = json.dumps(cli_output).encode()

        # Mock the subprocess execution
        with patch("asyncio.create_subprocess_exec", new_callable=AsyncMock) as mock_exec:
            mock_proc = MagicMock()
            mock_proc.communicate = AsyncMock(return_value=(stdout_bytes, b""))
            mock_proc.returncode = 0
            mock_exec.return_value = mock_proc

            # Create a dummy case
            case = ApiUnderstandingBenchmarkCase(
                name="Test", description="Test", category="Test",
                question="Test question", rationale="Test", file="test.py",
                template=AnswerTemplate.CLASS_DEFINITION, answers=[]
            )

            await generator.generate_answer(case)
            
            # Verify arguments
            args, _ = mock_exec.call_args
            cmd = list(args)
            
            # Check for Docker parts
            assert "docker" in cmd
            assert "run" in cmd
            assert "--rm" in cmd
            assert "-e" in cmd
            assert "GEMINI_API_KEY" in cmd
            assert "my-image:latest" in cmd
            
            # Check for Gemini CLI parts
            assert "gemini" in cmd
            assert "--output-format" in cmd
            assert "json" in cmd
            assert "--model" in cmd
            assert "gemini-2.5-flash" in cmd

@pytest.mark.asyncio
async def test_docker_command_construction_vertex_adc():
    """Test that Docker command handles Vertex AI and ADC mounting correctly."""

    env_vars = {
        "GOOGLE_GENAI_USE_VERTEXAI": "true",
        "GOOGLE_CLOUD_PROJECT": "my-project",
        "GOOGLE_APPLICATION_CREDENTIALS": "/local/path/creds.json"
    }

    with patch.dict(os.environ, env_vars, clear=True):
        generator = GeminiCliDockerAnswerGenerator(image_name="my-image:latest")

        # Inner model JSON
        inner_model_json = {
            "code": "class Vertex:",
            "fully_qualified_class_name": "vertex.Test",
            "rationale": "Vertex logic."
        }
        # CLI wrapper
        cli_output = {
            "response": json.dumps(inner_model_json) # Model might assume just raw JSON too
        }
        stdout_bytes = json.dumps(cli_output).encode()

        with patch("asyncio.create_subprocess_exec", new_callable=AsyncMock) as mock_exec:
            mock_proc = MagicMock()
            mock_proc.communicate = AsyncMock(return_value=(stdout_bytes, b""))
            mock_proc.returncode = 0
            mock_exec.return_value = mock_proc

            case = ApiUnderstandingBenchmarkCase(
                name="Test", description="Test", category="Test",
                question="Test", rationale="Test", file="test.py",
                template=AnswerTemplate.CLASS_DEFINITION, answers=[]
            )

            await generator.generate_answer(case)
            
            # Check arguments
            args, _ = mock_exec.call_args
            cmd = list(args)
            
            # Vertex AI Env vars
            assert "GOOGLE_GENAI_USE_VERTEXAI" in cmd
            assert "GOOGLE_CLOUD_PROJECT" in cmd
            assert "GOOGLE_APPLICATION_CREDENTIALS=/tmp/google_credentials.json" in [
                arg for arg in cmd if arg.startswith("GOOGLE_APPLICATION_CREDENTIALS=")
            ]
            
            # Volume mount
            assert "-v" in cmd
            assert "/local/path/creds.json:/tmp/google_credentials.json" in cmd
